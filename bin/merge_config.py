#!/usr/bin/env python
"""Write a site's _quarto.yml by merging its _quarto-site.yml into the shared one.

    python bin/merge_config.py [--check] [DIR]

DIR (default: the current directory, or pixi's INIT_CWD when run as the
`merge-config` task) holds the site's `_quarto-site.yml`; `DIR/_quarto.yml` is
overwritten with the shared `_quarto.yml` of this template, merged with it the
way Quarto merges a profile: a mapping merges key by key, a list is appended
to (dropping exact duplicates), and anything else is replaced. The shared
file's `profile` group is left out, so Quarto does not merge
`_quarto-site.yml` a second time.

For a site that needs a setting Quarto reads only from `_quarto.yml` itself,
not from a profile file: `metadata-files` (and `metadata-file`), which Quarto
expands when it reads `_quarto.yml`, before it merges any profile.

With --check, nothing is written: exits non-zero if DIR/_quarto.yml is not
what the merge gives.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

import yaml

SHARED = Path(__file__).resolve().parent.parent / "_quarto.yml"
HEADER = """\
# GENERATED by bin/merge_config.py of https://github.com/ickc/quarto-template
# from its shared `_quarto.yml` and this site's `_quarto-site.yml`. Do not edit
# it: edit `_quarto-site.yml`, then regenerate it with
#
#     pixi run -m <a clone of the template> merge-config <this directory>
#
# See the shared `_quarto.yml` for what its settings do, with comments.

"""


def merge(base, over):
    """Quarto's merge of a profile (`over`) into the config (`base`)."""
    if isinstance(base, dict) and isinstance(over, dict):
        out = dict(base)
        for key, value in over.items():
            out[key] = merge(base[key], value) if key in base else value
        return out
    if isinstance(base, list) or isinstance(over, list):
        combined = (base if isinstance(base, list) else [base]) + (over if isinstance(over, list) else [over])
        seen, out = set(), []
        for item in combined:
            key = json.dumps(item, sort_keys=True)
            if key not in seen:
                seen.add(key)
                out.append(item)
        return out
    return over


class Dumper(yaml.SafeDumper):
    pass


def _str(dumper, data):
    style = "|" if "\n" in data else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)


Dumper.add_representer(str, _str)


def render(site_dir: Path) -> str:
    shared = yaml.safe_load(SHARED.read_text())
    shared.pop("profile", None)
    site = yaml.safe_load((site_dir / "_quarto-site.yml").read_text()) or {}
    merged = merge(shared, site)
    return HEADER + yaml.dump(merged, Dumper=Dumper, sort_keys=False, allow_unicode=True, width=1000)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true")
    parser.add_argument("dir", nargs="?", default=".")
    args = parser.parse_args()

    site_dir = Path(os.environ.get("INIT_CWD", os.getcwd())) / args.dir
    out = site_dir / "_quarto.yml"
    text = render(site_dir)
    if args.check:
        if out.exists() and out.read_text() == text:
            return 0
        print(f"{out} is not the merge of the template's _quarto.yml and _quarto-site.yml")
        return 1
    out.write_text(text)
    print(f"{out} written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
